import AppKit

struct ClipboardItem: Identifiable, Equatable {
    enum Content: Equatable {
        case text(String)
        case image(NSImage)
    }

    let id = UUID()
    let content: Content
    let date: Date

    var text: String? {
        if case .text(let value) = content { return value }
        return nil
    }
}

/// Watches the general pasteboard and keeps a short history.
/// Text is persisted across launches; images live in memory only.
final class ClipboardMonitor: ObservableObject {
    @Published private(set) var items: [ClipboardItem] = []

    private let maxItems = 40
    private let storageKey = "clipboardHistory"
    private let settings: AppSettings
    private let pasteboard = NSPasteboard.general
    private var changeCount: Int
    private var timer: Timer?

    /// Types password managers set to ask clipboard tools not to record the copy.
    private let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
    ]

    init(settings: AppSettings) {
        self.settings = settings
        changeCount = pasteboard.changeCount
        let saved = UserDefaults.standard.stringArray(forKey: storageKey) ?? []
        items = saved.map { ClipboardItem(content: .text($0), date: .distantPast) }

        timer = Timer.scheduledTimer(withTimeInterval: 0.6, repeats: true) { [weak self] _ in
            self?.poll()
        }
    }

    private func poll() {
        guard pasteboard.changeCount != changeCount else { return }
        changeCount = pasteboard.changeCount
        guard settings.clipboardEnabled else { return }

        let types = Set(pasteboard.types?.map(\.rawValue) ?? [])
        guard types.isDisjoint(with: ignoredTypes) else { return }

        if let string = pasteboard.string(forType: .string),
           !string.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            insert(ClipboardItem(content: .text(string), date: Date()))
        } else if let image = NSImage(pasteboard: pasteboard) {
            insert(ClipboardItem(content: .image(image), date: Date()))
        }
    }

    private func insert(_ item: ClipboardItem) {
        if let text = item.text {
            items.removeAll { $0.text == text }
        }
        items.insert(item, at: 0)
        if items.count > maxItems { items.removeLast(items.count - maxItems) }
        save()
    }

    func copy(_ item: ClipboardItem) {
        pasteboard.clearContents()
        switch item.content {
        case .text(let text): pasteboard.setString(text, forType: .string)
        case .image(let image): pasteboard.writeObjects([image])
        }
        // Treat our own write as a normal copy so the item moves to the top.
        changeCount = -1
        poll()
    }

    func remove(_ item: ClipboardItem) {
        items.removeAll { $0.id == item.id }
        save()
    }

    func clear() {
        items.removeAll()
        save()
    }

    private func save() {
        UserDefaults.standard.set(items.compactMap(\.text), forKey: storageKey)
    }
}
